// Parses a WSC-style order taxon list (XLSX) and emits a SQL file with
// taxonomy / taxonomy_name INSERTs for manual review (see taxa-importer.prompt.md).
// Usage: node taxa-importer.js <path-to-order.xlsx> <path-to-output.sql>
const fs = require('fs');
const path = require('path');
const XLSX = require('xlsx');
const mysql = require('mysql');
const { getFullName } = require('../taxonomy-common');

// canonical order ids seeded by db/sql/order-tables.sql
const ORDERS = ['Araneae', 'Solifugae', 'Scorpiones', 'Palpigradi', 'Uropygi',
    'Amblypygi', 'Schizomida', 'Pseudoscorpiones', 'Ricinulei', 'Opiliones'];

const SUBGENUS_RE = /^\(.+\)\.?$/;
const LOWERCASE_WORD_RE = /^[a-z][a-z-]*$/;

const e = (v) => mysql.escape(v === undefined ? null : v);

const getOrderFromFilename = (inputPath) => {
    const base = path.basename(inputPath, path.extname(inputPath));
    const match = ORDERS.find(o => o.toLowerCase() === base.toLowerCase());
    if (!match) {
        throw new Error(`Unable to determine order from filename "${base}". Expected one of: ${ORDERS.join(', ')}`);
    }
    return match;
};

// splits raw column-A text into non-whitespace tokens, keeping original start/end offsets
const tokenize = (text) => {
    const tokens = [];
    const re = /\S+/g;
    let m;
    while ((m = re.exec(text)) !== null) {
        tokens.push({ value: m[0], start: m.index, end: m.index + m[0].length });
    }
    return tokens;
};

// strips leading extinct(†)/uncertain(?)/synonym(=) markers in any order/combination
const stripMarkers = (raw) => {
    let text = raw;
    let sawUncertain = false;
    let isSynonym = false;
    while (text.length > 0 && '†?='.includes(text[0])) {
        if (text[0] === '?') sawUncertain = true;
        if (text[0] === '=') isSynonym = true;
        text = text.slice(1);
    }
    return { text: text.trim(), skip: sawUncertain, isSynonym };
};

const extractYear = (author) => {
    if (!author) return null;
    const matches = author.match(/\d{4}/g);
    if (!matches) return null;
    return parseInt(matches[matches.length - 1], 10);
};

const parseFamilyOrGenus = (text) => {
    const tokens = tokenize(text);
    if (tokens.length === 0) return null;
    const name = tokens[0].value;
    const author = text.slice(tokens[0].end).trim() || null;
    return { name, author };
};

const parseSpecies = (text) => {
    const tokens = tokenize(text);
    if (tokens.length < 2) return null;
    let idx = 0;
    const genus = tokens[idx].value; idx++;
    let subgenus = null;
    if (tokens[idx] && SUBGENUS_RE.test(tokens[idx].value)) {
        subgenus = tokens[idx].value.replace(/^\(|\)\.?$/g, '');
        idx++;
    }
    if (!tokens[idx]) return null;
    const species = tokens[idx].value; idx++;
    let subspecies = null;
    if (tokens[idx] && LOWERCASE_WORD_RE.test(tokens[idx].value)) {
        subspecies = tokens[idx].value;
        idx++;
    }
    const authorStart = tokens[idx] ? tokens[idx].start : text.length;
    const author = text.slice(authorStart).trim() || null;
    return { genus, subgenus, species, subspecies, author };
};

const run = () => {
    const [, , inputPath, outputPath] = process.argv;
    if (!inputPath || !outputPath) {
        console.error('Usage: node taxa-importer.js <input.xlsx> <output.sql>');
        process.exit(1);
    }
    if (!fs.existsSync(inputPath)) {
        console.error(`Input file not found: ${inputPath}`);
        process.exit(1);
    }

    const order = getOrderFromFilename(inputPath);

    const wb = XLSX.readFile(inputPath);
    const sheetName = wb.SheetNames[0];
    const rows = XLSX.utils.sheet_to_json(wb.Sheets[sheetName], { header: 1, raw: false, defval: '' });

    // skip any header row(s) - real data starts once column B ends with ']'
    const startIndex = rows.findIndex(r => r[1] && /\]\s*$/.test(String(r[1]).trim()));
    if (startIndex === -1) {
        console.error('No data rows found (column B never ends with "]")');
        process.exit(1);
    }

    const sqlLines = [];
    sqlLines.push(`-- Generated by taxa-importer.js from ${path.basename(inputPath)} on ${new Date().toISOString()}`);
    sqlLines.push(`-- Order: ${order}`);
    sqlLines.push('');

    let currentFamily = null;
    let currentGenus = null;
    const counts = { family: 0, genus: 0, species: 0, synonym: 0, skipped: 0 };

    for (let i = startIndex; i < rows.length; i++) {
        const row = rows[i];
        const rawName = row[0] !== undefined ? String(row[0]).trim() : '';
        const rawRank = row[1] !== undefined ? String(row[1]).trim() : '';
        if (!rawName || !rawRank) continue;

        const rank = rawRank.replace(/\]\s*$/, '').trim().toLowerCase();
        const { text, skip, isSynonym } = stripMarkers(rawName);

        if (skip) {
            counts.skipped++;
            continue;
        }

        if (rank === 'order') {
            const parsed = parseFamilyOrGenus(text);
            if (parsed && parsed.name.toLowerCase() !== order.toLowerCase()) {
                console.warn(`Warning (row ${i + 1}): order row name "${parsed.name}" doesn't match filename-derived order "${order}"`);
            }
            continue;
        }

        let record = null;

        if (rank === 'family') {
            const parsed = parseFamilyOrGenus(text);
            if (!parsed) { console.warn(`Warning (row ${i + 1}): could not parse family row: "${rawName}"`); continue; }
            record = { family: parsed.name, genus: null, species: null, subspecies: null, author: parsed.author, year: extractYear(parsed.author) };
            if (!isSynonym) currentFamily = parsed.name;
        } else if (rank === 'genus') {
            const parsed = parseFamilyOrGenus(text);
            if (!parsed) { console.warn(`Warning (row ${i + 1}): could not parse genus row: "${rawName}"`); continue; }
            record = { family: currentFamily, genus: parsed.name, species: null, subspecies: null, author: parsed.author, year: extractYear(parsed.author) };
            if (!isSynonym) currentGenus = parsed.name;
        } else if (rank === 'species') {
            const parsed = parseSpecies(text);
            if (!parsed) { console.warn(`Warning (row ${i + 1}): could not parse species row: "${rawName}"`); continue; }
            if (!isSynonym && currentGenus && parsed.genus !== currentGenus) {
                console.warn(`Warning (row ${i + 1}): species genus "${parsed.genus}" doesn't match current genus context "${currentGenus}"`);
            }
            record = { family: currentFamily, genus: parsed.genus, species: parsed.species, subspecies: parsed.subspecies, author: parsed.author, year: extractYear(parsed.author) };
            if (parsed.subgenus) {
                sqlLines.push(`-- subgenus (${parsed.subgenus}) omitted for "${parsed.genus} ${parsed.species}" (no column in schema)`);
            }
        } else {
            console.warn(`Warning (row ${i + 1}): unknown rank "${rank}", skipping`);
            counts.skipped++;
            continue;
        }

        const fullName = getFullName(record);

        if (!isSynonym) {
            sqlLines.push(`INSERT INTO taxonomy (wsc_lsid, \`order\`, family, genus, species, subspecies, author, year, valid, full_name) `
                + `VALUES (NULL, ${e(order)}, ${e(record.family)}, ${e(record.genus)}, ${e(record.species)}, ${e(record.subspecies)}, ${e(record.author)}, ${e(record.year)}, 1, ${e(fullName)});`);
            sqlLines.push('SET @last_taxon_id = LAST_INSERT_ID();');
            counts[rank]++;
        } else {
            sqlLines.push(`INSERT IGNORE INTO taxonomy_name (taxonomy_id, name, valid) VALUES (@last_taxon_id, ${e(fullName)}, 1);`);
            counts.synonym++;
        }
    }

    fs.writeFileSync(outputPath, sqlLines.join('\n') + '\n');

    console.log(`Order: ${order}`);
    console.log(`Families: ${counts.family}, Genera: ${counts.genus}, Species: ${counts.species}, Synonyms: ${counts.synonym}`);
    console.log(`Skipped (uncertain): ${counts.skipped}`);
    console.log(`Output written to: ${outputPath}`);
};

run();
